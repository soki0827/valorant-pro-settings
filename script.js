// eDPI計算
// =========================

function getEDPI(player) {
  return player.dpi * player.sens;
}


// =========================
// 選手一覧表示
// =========================

function renderPlayers(list) {

  const container = document.getElementById("playerList");

  if (!container) return;

  container.innerHTML = "";

  const resultCount =
    document.getElementById("resultCount");

  if (resultCount) {
    resultCount.textContent = `${list.length}人`;
  }


  list.forEach(player => {

    const card =
      document.createElement("div");

    card.className = "player-card";


    card.onclick = () => {
      showPlayerDetail(player.name);
    };


    card.innerHTML = `

      <div class="player-name">
        ${player.name}
      </div>

      <div class="player-team">
        ${player.team}
      </div>


      <div class="player-info">


        <div class="stat">
          <span class="stat-label">
            ROLE
          </span>

          <span class="stat-value">
            ${player.role}
          </span>
        </div>


        <div class="stat">
          <span class="stat-label">
            DPI
          </span>

          <span class="stat-value">
            ${player.dpi}
          </span>
        </div>


        <div class="stat">
          <span class="stat-label">
            SENS
          </span>

          <span class="stat-value">
            ${player.sens}
          </span>
        </div>


        <div class="stat">
          <span class="stat-label">
            eDPI
          </span>

          <span class="stat-value">
            ${getEDPI(player).toFixed(1)}
          </span>
        </div>


      </div>

    `;


    container.appendChild(card);

  });

}


// =========================
// フィルター
// =========================

function filterPlayers(){

  const search =
    document.getElementById("searchInput")?.value
    .toLowerCase() || "";


  const region =
    document.getElementById("regionFilter")?.value
    || "all";


  const country =
    document.getElementById("countryFilter")?.value
    || "all";


  const role =
    document.getElementById("roleFilter")?.value
    || "all";


  const edpi =
    document.getElementById("edpiFilter")?.value
    || "all";


  const sens =
    document.getElementById("sensFilter")?.value
    || "all";



  const filtered =
    players.filter(player=>{


      const edpiValue =
        getEDPI(player);



      const searchOK =
        player.name.toLowerCase()
        .includes(search)

        ||

        player.team.toLowerCase()
        .includes(search);



      const regionOK =
        region==="all"
        ||
        player.region===region;



      const countryOK =
        country==="all"
        ||
        player.country===country;



      const roleOK =
        role==="all"
        ||
        player.role===role;



      let edpiOK=true;


      if(edpi==="low"){
        edpiOK =
          edpiValue>=100 &&
          edpiValue<200;
      }


      if(edpi==="mid"){
        edpiOK =
          edpiValue>=200 &&
          edpiValue<300;
      }


      if(edpi==="high"){
        edpiOK =
          edpiValue>=300 &&
          edpiValue<400;
      }


      if(edpi==="veryhigh"){
        edpiOK =
          edpiValue>=400;
      }



      let sensOK=true;


      if(sens==="low"){
        sensOK =
          player.sens>=0.10 &&
          player.sens<0.20;
      }


      if(sens==="mid"){
        sensOK =
          player.sens>=0.20 &&
          player.sens<0.30;
      }


      if(sens==="high"){
        sensOK =
          player.sens>=0.30 &&
          player.sens<0.40;
      }


      if(sens==="veryhigh"){
        sensOK =
          player.sens>=0.40;
      }



      return (
        searchOK &&
        regionOK &&
        countryOK &&
        roleOK &&
        edpiOK &&
        sensOK
      );


    });



  renderPlayers(filtered);

}


// =========================
// eDPI計算機
// =========================

function calculateEDPI(){

  const dpi =
    Number(
      document.getElementById("dpiInput").value
    );


  const sens =
    Number(
      document.getElementById("sensInput").value
    );


  const result =
    document.getElementById("edpiResult");


  if(!result)return;


  result.textContent =
    (dpi*sens).toFixed(1);

}


// =========================
// 詳細表示
// =========================

function showPlayerDetail(name){


  const player =
    players.find(
      p=>p.name===name
    );


  if(!player)return;


  const list =
    document.getElementById("playerList");


  const detail =
    document.getElementById("playerDetail");


  list.style.display="none";


  detail.classList.remove("hidden");


  detail.innerHTML = `


  <h2>
    ${player.name}
  </h2>


  <p>
    ${player.team}
  </p>


  <hr>


  <p>
    ROLE : ${player.role}
  </p>


  <p>
    DPI : ${player.dpi}
  </p>


  <p>
    SENS : ${player.sens}
  </p>


  <p>
    eDPI : ${getEDPI(player).toFixed(1)}
  </p>


  <p>
    🖱️ ${player.mouse}
  </p>


  <p>
    🖱️PAD : ${player.mousepad}
  </p>


  <button onclick="closePlayerDetail()">
    ← 戻る
  </button>


  `;


}


// =========================
// 戻る
// =========================

function closePlayerDetail(){

  document
  .getElementById("playerDetail")
  .classList.add("hidden");


  document
  .getElementById("playerList")
  .style.display="grid";

}



// =========================
// 起動
// =========================

document.addEventListener(
"DOMContentLoaded",
()=>{


  renderPlayers(players);



  document
  .querySelectorAll("select,input")
  .forEach(el=>{

    el.addEventListener(
      "input",
      filterPlayers
    );

    el.addEventListener(
      "change",
      filterPlayers
    );

  });


});
