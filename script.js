// =========================
// 絞り込み
// =========================

function filterPlayers() {

  const searchInput =
    document.getElementById("searchInput");

  const regionFilter =
    document.getElementById("regionFilter");

  const countryFilter =
    document.getElementById("countryFilter");

  const roleFilter =
    document.getElementById("roleFilter");

  const edpiFilter =
    document.getElementById("edpiFilter");

  const sensFilter =
    document.getElementById("sensFilter");


  const search =
    searchInput
      ? searchInput.value.trim().toLowerCase()
      : "";


  const region =
    regionFilter
      ? regionFilter.value
      : "all";


  const country =
    countryFilter
      ? countryFilter.value
      : "all";


  const role =
    roleFilter
      ? roleFilter.value
      : "all";


  const edpiValue =
    edpiFilter
      ? edpiFilter.value
      : "all";


  const sensValue =
    sensFilter
      ? sensFilter.value
      : "all";


  const filtered =
    players.filter(player => {


      const edpi =
        getEDPI(player);


      // -------------------------
      // 検索
      // -------------------------

      const searchMatch =
        player.name
          .toLowerCase()
          .includes(search) ||

        player.team
          .toLowerCase()
          .includes(search);


      // -------------------------
      // 地域
      // -------------------------

      const regionMatch =
        region === "all" ||
        player.region === region;


      // -------------------------
      // 国籍
      // -------------------------

      const countryMatch =
        country === "all" ||
        player.country === country;


      // -------------------------
      // ロール
      // -------------------------

      const roleMatch =
        role === "all" ||
        player.role === role;


      // -------------------------
      // eDPI
      // -------------------------

      let edpiMatch = true;


      if (edpiValue !== "all") {

        if (edpi === null) {

          edpiMatch = false;

        } else if (edpiValue === "low") {

          edpiMatch =
            edpi >= 100 &&
            edpi < 200;

        } else if (edpiValue === "mid") {

          edpiMatch =
            edpi >= 200 &&
            edpi < 300;

        } else if (edpiValue === "high") {

          edpiMatch =
            edpi >= 300 &&
            edpi < 400;

        } else if (edpiValue === "veryhigh") {

          edpiMatch =
            edpi >= 400;

        }

      }


      // -------------------------
      // 感度
      // -------------------------

      let sensMatch = true;


      if (sensValue !== "all") {

        if (
          typeof player.sens !== "number" ||
          player.sens <= 0
        ) {

          sensMatch = false;

        } else if (sensValue === "low") {

          sensMatch =
            player.sens >= 0.10 &&
            player.sens < 0.20;

        } else if (sensValue === "mid") {

          sensMatch =
            player.sens >= 0.20 &&
            player.sens < 0.30;

        } else if (sensValue === "high") {

          sensMatch =
            player.sens >= 0.30 &&
            player.sens < 0.40;

        } else if (sensValue === "veryhigh") {

          sensMatch =
            player.sens >= 0.40;

        }

      }


      return (
        searchMatch &&
        regionMatch &&
        countryMatch &&
        roleMatch &&
        edpiMatch &&
        sensMatch
      );

    });


  renderPlayers(filtered);

}


// =========================
// 検索
// =========================

function searchPlayers() {

  filterPlayers();

}


// =========================
// eDPI計算機
// =========================

function calculateEDPI() {

  const dpiInput =
    document.getElementById("dpiInput");

  const sensInput =
    document.getElementById("sensInput");

  const result =
    document.getElementById("edpiResult");


  if (
    !dpiInput ||
    !sensInput ||
    !result
  ) {

    return;

  }


  const dpi =
    Number(dpiInput.value);

  const sens =
    Number(sensInput.value);


  if (
    !Number.isFinite(dpi) ||
    !Number.isFinite(sens) ||
    dpi <= 0 ||
    sens < 0
  ) {

    result.textContent = "0.0";

    return;

  }


  const edpi =
    dpi * sens;


  result.textContent =
    edpi.toFixed(1);

}


