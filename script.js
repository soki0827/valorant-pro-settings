// =========================
// 選手詳細ページを閉じる
// =========================

function closePlayerDetail() {

  const list =
    document.getElementById("playerList");

  const detail =
    document.getElementById("playerDetail");


  if (!list || !detail) return;


  detail.classList.add(
    "hidden"
  );


  list.style.display =
    "grid";

}


